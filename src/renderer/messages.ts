// Built-in disk kinds as shared/targets.ts names them in its reasons (INTERNAL_WORDS).
const KINDS: Array<[string, string]> = [['eMMC', '内置 eMMC'], ['SD card slot', '内置 SD 卡槽'], ['NVMe drive', '内置 NVMe 硬盘'], ['internal disk', '内置磁盘']];
const kind = KINDS.map(([en]) => en.replace(/ /g, '\\s')).join('|');
const kindZh = (en: string) => KINDS.find(([e]) => e === en)?.[1] ?? en;

/** A pattern whose $1 is a disk kind: its Chinese is filled in here, once per kind. */
function perKind(re: (k: string) => RegExp, zh: (k: string) => string): Array<[RegExp, Record<Lang, string>]> {
  return KINDS.map(([en]) => [re(en), d('', zh(kindZh(en)))]);
}

